pub fn mono_points(waveform: &Waveform) -> Vec<i32> {
    waveform
        .points
        .iter()
        .map(|point| i32::from(*point))
        .collect()
}

pub fn stereo_points(waveform: &Waveform, right_divisor: i32) -> Vec<i32> {
    waveform
        .points
        .iter()
        .flat_map(|point| [i32::from(*point), i32::from(*point) / right_divisor])
        .collect()
}

pub fn wav16(waveform: &Waveform) -> Vec<u8> {
    write_wav(&WavSpec::mono16(SAMPLE_RATE), &mono_points(waveform))
}

pub fn flac16(waveform: &Waveform) -> Vec<u8> {
    let spec = FlacSpec {
        rate: SAMPLE_RATE,
        channels: 1,
        bits: 16,
    };
    write_flac(&spec, &mono_points(waveform))
}

pub fn sine_ogg() -> Vec<u8> {
    write_vorbis(&VorbisSpec::tone(SAMPLE_RATE, SINE_PACKETS, SINE_BIN))
}

fn write(path: &Path, bytes: &[u8]) -> io::Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, bytes)
}

fn shifted(points: Vec<i32>) -> Vec<i32> {
    points
        .into_iter()
        .map(|point| point << TWENTY_FOUR_BIT_SHIFT)
        .collect()
}

pub fn write_tiny_sfz(dir: &Path) -> io::Result<PathBuf> {
    let root = dir.join(TINY_SFZ_FOLDER);
    let programs = root.join("Programs");
    let sample_dir = root.join("Samples");
    write(&programs.join("guitar.sfz"), GUITAR_SFZ.as_bytes())?;
    write(&programs.join("bass.sfz"), BASS_SFZ.as_bytes())?;
    write(&programs.join("lead.sfz"), LEAD_SFZ.as_bytes())?;
    write(&programs.join("drum kit.sfz"), KIT_SFZ.as_bytes())?;
    let includes = programs.join("includes");
    write(&includes.join("kit-common.sfz"), KIT_COMMON_SFZ.as_bytes())?;
    write(&includes.join("hats.txt"), HATS_TXT.as_bytes())?;
    write(&includes.join("toms.txt"), TOMS_TXT.as_bytes())?;
    write(&root.join(SIDECAR_FILE), SIDECAR.as_bytes())?;
    write(&sample_dir.join("Pluck A3.wav"), &wav16(&samples::pluck()))?;
    write(
        &sample_dir.join("pluck soft.flac"),
        &flac16(&samples::pluck()),
    )?;
    write(&sample_dir.join("sine A4.ogg"), &sine_ogg())?;
    let bass = WavSpec {
        rate: SAMPLE_RATE,
        channels: 1,
        bits: 24,
        extensible: true,
    };
    write(
        &sample_dir.join("saw e2.wav"),
        &write_wav(&bass, &shifted(mono_points(&samples::saw_bass()))),
    )?;
    let kick = FlacSpec {
        rate: SAMPLE_RATE,
        channels: 2,
        bits: 24,
    };
    write(
        &sample_dir.join("kick.flac"),
        &write_flac(&kick, &shifted(stereo_points(&samples::kick(), 2))),
    )?;
    write(&sample_dir.join("snare 1.wav"), &wav16(&samples::snare()))?;
    write(
        &sample_dir.join("snare 2.wav"),
        &wav16(&samples::snare_variant()),
    )?;
    write(&sample_dir.join("hat closed.wav"), &wav16(&samples::hat()))?;
    let stereo = WavSpec {
        rate: SAMPLE_RATE,
        channels: 2,
        bits: 16,
        extensible: false,
    };
    write(
        &sample_dir.join("hat open.wav"),
        &write_wav(&stereo, &stereo_points(&samples::open_hat(), 3)),
    )?;
    Ok(root)
}

pub fn tiny_sfz(dir: &Path) -> PathBuf {
    match write_tiny_sfz(dir) {
        Ok(root) => root,
        Err(error) => panic!("cannot write the tiny SFZ bank: {error}"),
    }
}
